def semester_week(d: date) -> int:
    return (d - SEMESTER_START).days // 7 + 1


def exam_dt(course: str, moed: str = "a") -> datetime | None:
    from planner import TZ
    v = EXAMS.get(course, {}).get(moed)
    return datetime.fromisoformat(v).replace(tzinfo=TZ) if v else None


def upcoming_exams(today: date, moed: str = "a") -> list[tuple[str, datetime, int]]:
    """(קורס, מועד, ימים עד) לכל מבחן שעוד לא עבר, לפי סדר."""
    out = []
    for c in EXAMS:
        dt = exam_dt(c, moed)
        if dt and dt.date() >= today:
            out.append((c, dt, (dt.date() - today).days))
    return sorted(out, key=lambda x: x[1])


def topics_for_week(ws: date) -> dict[str, str]:
    """הנושא לפי הסילבוס בשבוע שמתחיל ב-ws, לכל קורס שיש לו חלוקה כזו."""
    out = {}
    n = semester_week(ws)
    for c, m in WEEKLY_TOPICS.items():
        if n in m:
            out[c] = m[n]
    for c, m in DATED_TOPICS.items():
        for ds, t in m.items():
            if ws <= date.fromisoformat(ds) < ws + timedelta(days=7):
                out[c] = t
    return out
